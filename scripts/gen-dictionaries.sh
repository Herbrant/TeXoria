#!/usr/bin/env bash
# Pin the Hunspell dictionaries that TeXoria downloads on demand (wooorm/dictionaries):
# writes crates/tex-spell/data/dictionaries.tsv with the SHA-256 of every index.aff/index.dic
# at COMMIT. Update COMMIT in crates/tex-spell/src/store.rs to the same value.
# Downloads every dictionary once (~300 MB).
set -euo pipefail

COMMIT="${1:?usage: gen-dictionaries.sh <wooorm/dictionaries commit>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/crates/tex-spell/data/dictionaries.tsv"
BASE="https://raw.githubusercontent.com/wooorm/dictionaries/$COMMIT/dictionaries"

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

codes="$(curl -fsSL "https://api.github.com/repos/wooorm/dictionaries/contents/dictionaries?ref=$COMMIT" |
  grep '"name"' | sed -E 's/.*"name": *"([^"]+)".*/\1/')"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
  echo "# Generated by scripts/gen-dictionaries.sh $COMMIT: code, SHA-256 of index.aff, of index.dic."
  for code in $codes; do
    curl -fsSL "$BASE/$code/index.aff" -o "$tmp/aff"
    curl -fsSL "$BASE/$code/index.dic" -o "$tmp/dic"
    printf '%s\t%s\t%s\n' "$code" "$(sha256 "$tmp/aff")" "$(sha256 "$tmp/dic")"
    echo "$code" >&2
  done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT"
